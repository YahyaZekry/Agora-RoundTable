#!/usr/bin/env bash
# Install the Agora RoundTable opencode plugin bundle into the global opencode config.
#
#   bash opencode-plugin/install.sh [config-dir]
#
# - config-dir defaults to $HOME/.config/opencode
# - Symlinks this bundle's commands/, agents/, and skills/ into the config so a
#   checkout stays the single source of truth (no drift).
# - Writes a small real *shim* for the JS plugin (see the note further down) rather
#   than symlinking it, because opencode's plugin loader cannot load a symlinked
#   entry point.
# - Creates the shared, agent-neutral persona data dir (~/.agora, or $AGORA_DATA_DIR)
#   so opencode, Claude, codex, etc. all use the same people. Data from older installs
#   that kept personas under the opencode config dir is migrated once.
#
# Works in-place from the repo. Safe to re-run (idempotent).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_DIR="${1:-$HOME/.config/opencode}"

BUNDLE_DIR="$SCRIPT_DIR"

mkdir -p "$CONFIG_DIR"

link() {
  # $1 = subdir name (commands|agents|skills)
  # $2 = destination subdir (may differ, e.g. plugin -> plugins)
  local sub="$1"
  local dstsub="${2:-$1}"
  local src="$BUNDLE_DIR/$sub"
  local dst="$CONFIG_DIR/$dstsub"
  if [ ! -d "$src" ]; then
    echo "  skip $sub (nothing in $src)"
    return
  fi
  mkdir -p "$dst"
  for item in "$src"/*; do
    [ -e "$item" ] || continue
    local name; name="$(basename "$item")"
    local target="$dst/$name"
    if [ -e "$target" ] && [ ! -L "$target" ]; then
      echo "  WARN $target exists and is not a symlink — leaving as-is"
      continue
    fi
    ln -sfn "$item" "$target"
    echo "  linked $target -> $item"
  done
}

# Absolute file:// URL for a path (percent-encodes spaces etc. when python3 is
# available; falls back to a plain file:// URL otherwise).
file_url() {
  local p="$1"
  if command -v python3 >/dev/null 2>&1; then
    python3 -c 'import pathlib,sys; print(pathlib.Path(sys.argv[1]).as_uri())' "$p"
  else
    printf 'file://%s' "$p"
  fi
}

echo "Installing Agora RoundTable into $CONFIG_DIR"

link commands
link agents
link skills

# The JS plugin is loaded by opencode's own module loader, which cannot load a
# plugin whose entry point is a symlink pointing outside the config dir (it fails
# to see the module's default export). So instead of symlinking plugin/plugin.js we
# write a tiny real shim that re-exports it from this checkout — the repo stays the
# single source of truth and the shim is nothing but a pointer.
PLUGIN_SRC="$BUNDLE_DIR/plugin/plugin.js"
PLUGINS_DIR="$CONFIG_DIR/plugins"
SHIM="$PLUGINS_DIR/plugin.js"
SHIM_MARK="Generated by the Agora RoundTable installer"
mkdir -p "$PLUGINS_DIR"
# Drop a stale symlink from an older install so we never write through it.
if [ -L "$SHIM" ]; then rm -f "$SHIM"; fi
if [ -e "$SHIM" ] && ! grep -q "$SHIM_MARK" "$SHIM" 2>/dev/null; then
  echo "  WARN $SHIM exists and is not ours — leaving as-is"
else
  cat > "$SHIM" <<EOF
// $SHIM_MARK. Do not edit.
// opencode's plugin loader cannot load a symlinked plugin entry point, so this
// real file re-exports the plugin from the checkout (single source of truth).
export { default } from "$(file_url "$PLUGIN_SRC")"
EOF
  echo "  wrote $SHIM -> $PLUGIN_SRC"
fi

# The plugin has no runtime dependencies (it uses opencode's own setup context),
# so there is nothing to install here.

# Persona data dir — agent-neutral, so no single tool owns it.
# Default ~/.agora (identical on Linux, macOS, Windows); override with $AGORA_DATA_DIR.
AGORA_DIR="${AGORA_DATA_DIR:-$HOME/.agora}"
mkdir -p "$AGORA_DIR/personas"
echo "  personas dir: $AGORA_DIR/personas (agent-neutral)"

# One-time migration from the old opencode-config-native location, only if the
# neutral dir is still empty and the legacy one has real (non-symlink) data.
LEGACY_AGORA="$CONFIG_DIR/agora"
if [ -d "$LEGACY_AGORA/personas" ] && [ ! -L "$LEGACY_AGORA/personas" ] \
   && [ -z "$(ls -A "$AGORA_DIR/personas" 2>/dev/null)" ]; then
  cp -a "$LEGACY_AGORA/personas/." "$AGORA_DIR/personas/"
  echo "  migrated personas from $LEGACY_AGORA/personas"
fi

echo "Done. Commands are available as /agora* (restart opencode if they don't appear)."
